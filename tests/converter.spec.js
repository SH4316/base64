import { expect, test } from '@playwright/test'

test('encodes and decodes Unicode through the center buttons', async ({ page }) => {
  await page.goto('/')
  const plain = page.getByLabel('Plain text', { exact: true })
  const encoded = page.getByLabel('Base64', { exact: true })
  await expect(page.getByText('Your input is not sent to a server.', { exact: true })).toBeVisible()
  await plain.fill('안녕하세요 👋')
  await page.getByRole('button', { name: 'Encode', exact: true }).click()
  await expect(encoded).toHaveValue(Buffer.from('안녕하세요 👋').toString('base64'))
  await plain.fill('replace me')
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await expect(plain).toHaveValue('안녕하세요 👋')
  await encoded.fill('bad!')
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Invalid Base64 characters')
  await expect(plain).toHaveValue('안녕하세요 👋')
})

test('uploads binary files and downloads the original decoded bytes', async ({ page }) => {
  await page.goto('/')
  const bytes = Buffer.from([0, 255, 251, 128, 42])
  await page.getByLabel('Upload source file', { exact: true }).setInputFiles({ name: 'sample.bin', mimeType: 'application/octet-stream', buffer: bytes })
  await expect(page.getByText('sample.bin', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: 'URL-safe' }).check()
  await page.getByRole('checkbox', { name: 'Keep padding' }).uncheck()
  await page.getByRole('button', { name: 'Encode', exact: true }).click()
  await expect(page.getByLabel('Base64', { exact: true })).toHaveValue(bytes.toString('base64url'))
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Decoded a binary file')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download plain text or file', exact: true }).click()
  const download = await downloadEvent
  expect(download.suggestedFilename()).toBe('decoded.bin')
  const stream = await download.createReadStream()
  const chunks           = []
  for await (const chunk of stream ) chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks)).toEqual(bytes)
})

test('example, keyboard shortcuts, clipboard, and clear work without sending input', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const externalRequests           = []
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:4173/')) externalRequests.push(request.url()); expect(request.method()).toBe('GET') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Try an example' }).click()
  const plain = page.getByLabel('Plain text', { exact: true })
  await expect(plain).toHaveValue(/Hello, world!/)
  await plain.press('Control+Enter')
  const encoded = page.getByLabel('Base64', { exact: true })
  await expect(encoded).not.toHaveValue('')
  await page.getByRole('button', { name: 'Copy Base64', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(await encoded.inputValue())
  await page.getByRole('button', { name: 'Clear all' }).click()
  await expect(plain).toHaveValue('')
  await expect(encoded).toHaveValue('')
  expect(externalRequests).toEqual([])
})

test('keeps the editor order and all actions usable on narrow screens', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/')
  const plain = page.getByLabel('Plain text', { exact: true })
  const encoded = page.getByLabel('Base64', { exact: true })
  const encode = page.getByRole('button', { name: 'Encode', exact: true })
  await plain.fill('mobile')
  await encode.click()
  await expect(encoded).toHaveValue('bW9iaWxl')
  const positions = await Promise.all([plain.boundingBox(), encode.boundingBox(), encoded.boundingBox()])
  expect(positions[0] .y).toBeLessThan(positions[1] .y)
  expect(positions[1] .y).toBeLessThan(positions[2] .y)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
